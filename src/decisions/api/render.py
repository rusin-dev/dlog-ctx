"""Render extracted symbols into ``docs/api/<version>/<topic>/index.md``.

Design constraint: renderers only **return strings, never write files**. The
disk diff is computed in memory by :mod:`decisions.api.diff`, therefore
``sync`` never touches a confirmed baseline directory directly.

Section layout (anchor markers + optional callout):

```markdown
<!-- decisions:api:storage.Database.connect:start -->

## storage.Database.connect

```python
def connect(self, dsn: str) -> Connection
```

Human readable notes...

- **Module**: `storage`
- **Kind**: `method`
- **Defined in**: `src/storage.py:12`
- **Returns**: `Connection`
- **Status**: `active`

<!-- decisions:api:storage.Database.connect:end -->
```
"""

from __future__ import annotations

import posixpath
import re
from dataclasses import dataclass, field

from ..core.models import ApiSymbol, anchor, normalize_version

MARKER_RE = re.compile(r"<!--\s*decisions:api:(?P<name>.+?):(?P<kind>start|end)\s*-->")
META_RE = re.compile(r"^-\s+\*\*(?P<key>[^*]+)\*\*\s*:\s*(?P<value>.*)$")
FENCE_RE = re.compile(r"^```")

REMOVED_MARKER = "removed in the next version"
READDED_MARKER = "was re-added in"

HEADER_NOTE = (
    "> This file is generated by `decisions api sync`. Do not edit it by hand.\n"
    "> Each symbol section is delimited by `decisions:api` HTML comment markers"
    " so tooling can address it."
)


def doc_path(version: str, topic: str) -> str:
    """Repo-relative (posix) path of the doc that owns a topic."""
    return f"docs/api/{normalize_version(version)}/{topic}/index.md"


def anchor_of(qualified_name: str) -> str:
    """Heading anchor for ``qualified_name`` (GitHub slug rules)."""
    return anchor(qualified_name)


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def default_preamble(topic: str) -> str:
    """Preamble (title + generated-file note) for a fresh topic document."""
    return f"# {topic}\n\n{HEADER_NOTE}\n"


def render_meta_lines(symbol: ApiSymbol) -> list[str]:
    """Render the ``- **Key**: value`` metadata block of a symbol section."""
    lines = [
        f"- **Module**: `{symbol.module}`",
        f"- **Kind**: `{symbol.kind}`",
    ]
    if symbol.source_file:
        location = symbol.source_file
        if symbol.lineno:
            location += f":{symbol.lineno}"
        lines.append(f"- **Defined in**: `{location}`")
    if symbol.returns and symbol.status != "removed":
        lines.append(f"- **Returns**: `{symbol.returns}`")
    if symbol.decision_refs:
        refs = ", ".join(f"`{ref}`" for ref in symbol.decision_refs)
        lines.append(f"- **Decisions**: {refs}")
    if symbol.status == "removed":
        lines.append(f"- **Status**: `removed in {symbol.removed_in or '?'}`")
    else:
        lines.append("- **Status**: `active`")
    return lines


def render_section(
    symbol: ApiSymbol,
    *,
    version: str,
    existing: ParsedSection | None = None,
    tombstones: bool = True,
) -> str:
    """Render one complete symbol section including markers.

    ``existing`` is the same symbol's section from the baseline document. It is
    used to keep historical callouts (idempotency) and to detect symbols that
    were removed and later re-added.
    """
    if symbol.status == "removed" and not tombstones:
        return ""

    lines: list[str] = [f"<!-- decisions:api:{symbol.qualified_name}:start -->", ""]
    link = _self_link(symbol)

    callouts = list(existing.callouts) if existing else []
    if existing and existing.status == "removed":
        removed_in = existing.removed_in
        if removed_in and normalize_version(removed_in) == normalize_version(version):
            # Removed and re-added within the same version: drop the tombstone.
            callouts = [c for c in callouts if not (REMOVED_MARKER in c and f"[{removed_in}]" in c)]
        elif removed_in and not _callout_present(callouts, version, READDED_MARKER):
            callouts.append(f"> This API {READDED_MARKER} [{version}]({link}).")

    if symbol.status == "removed":
        removed_in = symbol.removed_in or version
        if not _callout_present(callouts, removed_in, REMOVED_MARKER):
            callouts.append(
                f"> [!IMPORTANT]\n> This API was {REMOVED_MARKER} [{removed_in}]({link})."
            )

    for callout in callouts:
        lines.extend(callout.splitlines())
        lines.append("")

    lines.extend([f"## {symbol.qualified_name}", ""])

    if symbol.status == "removed":
        lines.extend(
            [
                "_This symbol was removed from the implementation. The section is kept"
                " so that existing anchors stay valid._",
                "",
            ]
        )
    else:
        lines.extend(["```python", symbol.signature, "```", ""])
        if symbol.doc:
            lines.extend([symbol.doc.strip(), ""])

    lines.extend(render_meta_lines(symbol))
    lines.append("")
    lines.append(f"<!-- decisions:api:{symbol.qualified_name}:end -->")
    return "\n".join(lines)


def render_document(preamble: str, sections: list[str]) -> str:
    """Join a preamble and its sections into one Markdown document."""
    body = "\n\n".join(section for section in sections if section.strip())
    text = preamble.rstrip("\n")
    if body:
        text += "\n\n" + body
    return text.rstrip("\n") + "\n"


def _self_link(symbol: ApiSymbol) -> str:
    """Link to this symbol's own anchor, computed dynamically (never hardcoded)."""
    return posixpath.relpath(symbol.doc_path, posixpath.dirname(symbol.doc_path)) + (
        f"#{symbol.anchor()}"
    )


def _callout_present(callouts: list[str], version: str, marker: str) -> bool:
    version = normalize_version(version)
    return any(marker in callout and f"[{version}]" in callout for callout in callouts)


# ---------------------------------------------------------------------------
# Parsing (document -> structured sections)
# ---------------------------------------------------------------------------


@dataclass
class ParsedSection:
    """One ``decisions:api`` marker-delimited section of a rendered document."""

    name: str
    callouts: list[str] = field(default_factory=list)
    signature: str = ""
    doc: str = ""
    meta: dict[str, str] = field(default_factory=dict)
    raw: str = ""

    @property
    def status(self) -> str:
        """``"removed"`` for tombstone sections, ``"active"`` otherwise."""
        return "removed" if self.meta.get("Status", "active").startswith("removed") else "active"

    @property
    def removed_in(self) -> str | None:
        """Version recorded in the ``Status`` line, if the symbol was removed."""
        match = re.search(r"removed in (\S+)", self.meta.get("Status", ""))
        return match.group(1) if match else None

    @property
    def kind(self) -> str:
        """Symbol kind (``function``, ``class``, ...) from the metadata block."""
        return self.meta.get("Kind", "symbol")

    @property
    def module(self) -> str:
        """Module path recorded in the metadata block."""
        return self.meta.get("Module", "")

    @property
    def decision_refs(self) -> list[str]:
        """``@decision:`` back-references listed in the metadata block."""
        raw = self.meta.get("Decisions", "")
        refs: list[str] = []
        for item in raw.split(","):
            ref = item.strip().strip("`").strip()
            if ref and ref not in refs:
                refs.append(ref)
        return refs

    @property
    def source_file(self) -> str | None:
        """Source file from ``Defined in``, without the line suffix."""
        location = self.meta.get("Defined in", "")
        if not location:
            return None
        return location.rsplit(":", 1)[0] if _has_line_suffix(location) else location

    @property
    def lineno(self) -> int | None:
        """Line number from ``Defined in``, when present."""
        location = self.meta.get("Defined in", "")
        if not _has_line_suffix(location):
            return None
        try:
            return int(location.rsplit(":", 1)[1])
        except ValueError:
            return None

    def to_symbol(self, document_path: str) -> ApiSymbol:
        """Turn the parsed section back into an :class:`ApiSymbol`."""
        topic = topic_from_doc_path(document_path) or self.module.split(".")[0]
        return ApiSymbol(
            qualified_name=self.name,
            kind=self.kind,
            module=self.module,
            topic=topic,
            doc_path=document_path,
            signature=self.signature,
            returns=_strip_ticks(self.meta.get("Returns")),
            doc=self.doc or None,
            source_file=self.source_file,
            lineno=self.lineno,
            status=self.status,
            removed_in=self.removed_in,
            decision_refs=self.decision_refs,
        )


@dataclass
class ParsedDocument:
    """A rendered document split into its preamble and marker sections."""

    preamble: str = ""
    sections: dict[str, ParsedSection] = field(default_factory=dict)


def parse_document(text: str) -> ParsedDocument:
    """Parse a rendered document back into sections (index rebuild, idempotency)."""
    marks = list(MARKER_RE.finditer(text))
    if not marks:
        return ParsedDocument(preamble=text, sections={})

    preamble = text[: marks[0].start()]
    sections: dict[str, ParsedSection] = {}
    index = 0
    while index < len(marks):
        start = marks[index]
        if start.group("kind") != "start":
            index += 1
            continue
        end = None
        if index + 1 < len(marks) and marks[index + 1].group("kind") == "end":
            end = marks[index + 1]
            index += 2
        else:
            index += 1
        if end is None or end.group("name") != start.group("name"):
            continue
        name = start.group("name")
        sections[name] = _parse_section(name, text[start.end() : end.start()])
    return ParsedDocument(preamble=preamble, sections=sections)


def _parse_section(name: str, inner: str) -> ParsedSection:
    lines = inner.splitlines()
    callouts, rest = _split_leading_callouts(lines)
    section = ParsedSection(name=name, callouts=callouts, raw=inner)

    heading_idx = next((i for i, line in enumerate(rest) if line.startswith("#")), None)
    if heading_idx is not None:
        rest = rest[heading_idx + 1 :]

    fence_start = next((i for i, line in enumerate(rest) if FENCE_RE.match(line)), None)
    if fence_start is not None:
        fence_end = next(
            (i for i in range(fence_start + 1, len(rest)) if FENCE_RE.match(rest[i])),
            None,
        )
        if fence_end is not None:
            section.signature = "\n".join(rest[fence_start + 1 : fence_end]).strip()
            rest = rest[:fence_start] + rest[fence_end + 1 :]

    doc_lines: list[str] = []
    for line in rest:
        match = META_RE.match(line.strip())
        if match:
            key = match.group("key").strip()
            section.meta[key] = _strip_ticks(match.group("value").strip()) or ""
        elif section.meta:
            continue
        elif line.strip():
            doc_lines.append(line.rstrip())
    section.doc = "\n".join(doc_lines).strip()
    return section


def _split_leading_callouts(lines: list[str]) -> tuple[list[str], list[str]]:
    callouts: list[str] = []
    idx = 0
    while idx < len(lines):
        if not lines[idx].strip():
            idx += 1
            continue
        if not lines[idx].lstrip().startswith(">"):
            break
        block: list[str] = []
        while idx < len(lines) and (lines[idx].lstrip().startswith(">") or not lines[idx].strip()):
            block.append(lines[idx])
            idx += 1
        while block and not block[-1].strip():
            block.pop()
        if block:
            callouts.append("\n".join(block))
    return callouts, lines[idx:]


def _strip_ticks(value: str | None) -> str | None:
    if value is None:
        return None
    value = value.strip()
    if len(value) >= 2 and value.startswith("`") and value.endswith("`"):
        return value[1:-1]
    return value


def _has_line_suffix(location: str) -> bool:
    return bool(re.search(r":\d+$", location))


def topic_from_doc_path(path: str) -> str | None:
    """``docs/api/v1.3/storage/index.md`` -> ``storage``."""
    parts = path.split("/")
    if len(parts) >= 5 and parts[0] == "docs" and parts[1] == "api":
        return parts[3]
    return None


def symbols_from_docs(docs: dict[str, str]) -> list[ApiSymbol]:
    """Rebuild the symbol table from a rendered document tree."""
    symbols: list[ApiSymbol] = []
    for path in sorted(docs):
        parsed = parse_document(docs[path])
        for section in parsed.sections.values():
            symbols.append(section.to_symbol(path))
    return symbols


# ---------------------------------------------------------------------------
# Target document tree
# ---------------------------------------------------------------------------


def render_target(
    base_docs: dict[str, str],
    symbols: list[ApiSymbol],
    version: str,
    *,
    tombstones: bool = True,
) -> dict[str, str | None]:
    """Compute the target document tree in memory.

    - new symbol      -> append section
    - deleted symbol  -> drop the body and insert a ``removed_in`` callout
                         (tombstone, keeps the anchor alive)
    - changed symbol  -> replace the section, preserving historical callouts

    Returns ``{repo-relative path: content | None}``, where ``None`` deletes
    the file.
    """
    version = normalize_version(version)
    by_topic: dict[str, list[ApiSymbol]] = {}
    for symbol in symbols:
        by_topic.setdefault(symbol.topic, []).append(symbol)

    base_by_topic: dict[str, tuple[str, str]] = {}
    for path, text in base_docs.items():
        topic = topic_from_doc_path(path)
        if topic:
            base_by_topic[topic] = (path, text)

    target: dict[str, str | None] = {}
    for topic in sorted(set(by_topic) | set(base_by_topic)):
        path, text = base_by_topic.get(topic, (doc_path(version, topic), ""))
        parsed = parse_document(text) if text else ParsedDocument(default_preamble(topic))
        current = sorted(by_topic.get(topic, []), key=lambda s: s.qualified_name)
        names_now = {symbol.qualified_name for symbol in current}

        sections: list[str] = []
        for name, existing in parsed.sections.items():
            if name in names_now:
                symbol = next(s for s in current if s.qualified_name == name)
                rendered = render_section(
                    symbol, version=version, existing=existing, tombstones=tombstones
                )
                if rendered:
                    sections.append(rendered)
            elif tombstones:
                tombstone = existing.to_symbol(path)
                tombstone.status = "removed"
                tombstone.removed_in = version
                sections.append(
                    render_section(tombstone, version=version, existing=existing, tombstones=True)
                )

        known = set(parsed.sections)
        for symbol in current:
            if symbol.qualified_name in known:
                continue
            sections.append(render_section(symbol, version=version, tombstones=tombstones))

        if not sections:
            target[path] = None  # topic disappeared entirely
        else:
            target[path] = render_document(parsed.preamble, sections)
    return target
